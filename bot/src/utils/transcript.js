const { EmbedBuilder } = require('discord.js');
const db = require('../database/db');
const config = require('../../config.json');

function generateTranscriptHTML(ticket, messages, guild) {
  const date = new Date(ticket.createdAt).toLocaleString();
  const closeDate = ticket.closedAt ? new Date(ticket.closedAt).toLocaleString() : 'Still open';
  const closedBy = ticket.closedBy ? '<@' + ticket.closedBy + '>' : 'N/A';
  
  let messagesHtml = '';
  messages.forEach(m => {
    const time = new Date(m.timestamp || Date.now()).toLocaleTimeString();
    const author = m.author || 'Unknown';
    const content = String(m.content || '').replace(/</g, '<').replace(/>/g, '>');
    const isBot = m.authorBot || false;
    messagesHtml += `
      <div class="message ${isBot ? 'bot' : ''}">
        <span class="time">[${time}]</span>
        <span class="author" style="color: ${isBot ? '#5865f2' : '#fff'}">${author}:</span>
        <span class="content">${content}</span>
      </div>`;
  });

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>Ticket Transcript #${ticket.number}</title>
  <style>
    body { font-family: 'Segoe UI', sans-serif; background: #0d1117; color: #e6edf3; margin: 0; padding: 20px; }
    .container { max-width: 900px; margin: 0 auto; background: #161b22; border: 1px solid #30363d; border-radius: 12px; padding: 24px; }
    .header { border-bottom: 1px solid #30363d; padding-bottom: 16px; margin-bottom: 24px; }
    .header h1 { margin: 0 0 8px; color: #58a6ff; font-size: 24px; }
    .meta { display: grid; grid-template-columns: repeat(auto-fit, minmax(200px, 1fr)); gap: 12px; font-size: 14px; color: #8b949e; }
    .meta div { background: #0d1117; padding: 8px 12px; border-radius: 6px; border: 1px solid #21262d; }
    .meta strong { color: #e6edf3; }
    .messages { display: flex; flex-direction: column; gap: 12px; }
    .message { padding: 12px 16px; background: #0d1117; border: 1px solid #21262d; border-radius: 8px; line-height: 1.6; word-wrap: break-word; }
    .message.bot { border-color: #1f4287; background: #0d1b2a; }
    .time { color: #8b949e; font-size: 12px; margin-right: 8px; }
    .author { font-weight: 600; margin-right: 8px; }
    .footer { margin-top: 24px; padding-top: 16px; border-top: 1px solid #30363d; text-align: center; color: #8b949e; font-size: 12px; }
  </style>
</head>
<body>
  <div class="container">
    <div class="header">
      <h1>🎫 Ticket Transcript — #${ticket.number}</h1>
      <div class="meta">
        <div><strong>Type:</strong> ${ticket.type || 'General Support'}</div>
        <div><strong>Owner:</strong> <@${ticket.userId || 'unknown'}> (${ticket.userId || 'N/A'})</div>
        <div><strong>Status:</strong> ${ticket.status || 'unknown'}</div>
        <div><strong>Opened:</strong> ${date}</div>
        <div><strong>Closed:</strong> ${closeDate}</div>
        <div><strong>Closed by:</strong> ${closedBy}</div>
        <div><strong>Reason:</strong> ${ticket.reason || 'No reason provided'}</div>
        <div><strong>Server:</strong> ${guild?.name || 'Unknown'} (${guild?.id || 'N/A'})</div>
      </div>
    </div>
    <div class="messages">${messagesHtml}</div>
    <div class="footer">Generated by ${config.botName} • Powered by ${config.company} • ${new Date().toISOString()}</div>
  </div>
</body></html>`;
}

async function generateTranscript(ticket, channel) {
  const messages = [];
  let lastId = null;
  while (true) {
    const fetched = await channel.messages.fetch({ limit: 100, before: lastId }).catch(() => null);
    if (!fetched || fetched.size === 0) break;
    fetched.forEach(m => {
      messages.push({
        author: m.author.tag,
        authorBot: m.author.bot,
        content: m.content,
        timestamp: m.createdTimestamp
      });
    });
    lastId = fetched.last().id;
    if (fetched.size < 100) break;
  }
  messages.reverse();
  return messages;
}

async function sendTranscript(ticket, channel, guild) {
  const messages = await generateTranscript(ticket, channel);
  const html = generateTranscriptHTML(ticket, messages, guild);
  
  const { createWriteStream } = require('fs');
  const { join } = require('path');
  const transcriptDir = join(__dirname, '../../data/transcripts');
  if (!require('fs').existsSync(transcriptDir)) require('fs').mkdirSync(transcriptDir, { recursive: true });
  
  const fileName = `ticket-${ticket.number}-${ticket.id}.html`;
  const filePath = join(transcriptDir, fileName);
  require('fs').writeFileSync(filePath, html, 'utf8');
  
  return { filePath, fileName, messageCount: messages.length };
}

async function uploadTranscriptToLog(guild, settings, ticket, transcriptResult) {
  const logId = settings.ticketLogChannel || settings.logChannel;
  const logChannel = logId ? guild.channels.cache.get(logId) : null;
  if (!logChannel) return;
  
  const { AttachmentBuilder } = require('discord.js');
  const attachment = new AttachmentBuilder(transcriptResult.filePath, { name: transcriptResult.fileName });
  
  await logChannel.send({
    embeds: [new EmbedBuilder()
      .setColor(config.colors.primary)
      .setTitle('📄 Ticket Transcript Generated')
      .setDescription(
        '**Ticket:** #' + ticket.number + ' (' + ticket.type + ')\n' +
        '**Owner:** <@' + ticket.userId + '>\n' +
        '**Messages:** ' + transcriptResult.messageCount + '\n' +
        '**Closed by:** <@' + (ticket.closedBy || 'unknown') + '>'
      )
      .setTimestamp()],
    files: [attachment]
  }).catch(() => {});
}

async function dmTranscriptToUser(userId, guild, ticket, transcriptResult) {
  try {
    const user = await guild.client.users.fetch(userId);
    const { AttachmentBuilder } = require('discord.js');
    const attachment = new AttachmentBuilder(transcriptResult.filePath, { name: transcriptResult.fileName });
    await user.send({
      embeds: [new EmbedBuilder()
        .setColor(config.colors.primary)
        .setTitle('📄 Your Ticket Transcript')
        .setDescription('Transcript for ticket **#' + ticket.number + '** in **' + guild.name + '**.')
        .setTimestamp()],
      files: [attachment]
    }).catch(() => {});
  } catch (err) {
    console.error('DM transcript failed:', err.message);
  }
}

